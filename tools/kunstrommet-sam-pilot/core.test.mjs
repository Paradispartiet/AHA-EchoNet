import assert from "node:assert/strict";
import {WIDTH,HEIGHT,fixture,selectMask,maskCandidates,chooseCandidate,GUIDED_POINTS,CHALLENGES,challengeFixture,PHOTO_SPECS,validatePhotoPoints,intersectionOverUnion} from "./core.mjs";
const {truth,rgb}=fixture(),n=WIDTH*HEIGHT;
assert.equal(rgb.length,n*3);
const data=new Uint8Array(3*n);data.set(truth,n);data.fill(1,2*n);
const tensor={dims:[1,3,HEIGHT,WIDTH],type:"bool",data};
const best=selectMask(tensor,[.9,.8,.99],160,120);
assert.equal(best.channel,1);assert.equal(intersectionOverUnion(best.bits,truth),1);
assert.throws(()=>selectMask(tensor,[.9,.8,.99],0,0),/no_valid_mask/);
assert.throws(()=>selectMask({...tensor,dims:[3,HEIGHT,WIDTH]},[.9,.8,.99],160,120),/unexpected_model_output/);
assert.throws(()=>selectMask(tensor,[.9,.8,.99],WIDTH,0),/invalid_point/);
assert.equal(intersectionOverUnion(new Uint8Array(n),truth),0);
const guided=maskCandidates(tensor,[.9,.8,.99],GUIDED_POINTS);
assert.equal(guided[0].eligible,false);
assert.equal(guided[1].eligible,true);
assert.equal(guided[2].eligible,false);
assert.equal(chooseCandidate(guided).channel,1);
const partial=new Uint8Array(3*n);partial.set(truth,n);
partial[120*WIDTH+160]=1;
const choices=maskCandidates({...tensor,data:partial},[10,.1,0],GUIDED_POINTS);
assert.equal(choices[0].eligible,false);
assert.equal(chooseCandidate(choices).channel,1);
assert.throws(()=>maskCandidates(tensor,[.9,.8,.99],[[1,1,0]]),/invalid_point/);
assert.throws(()=>chooseCandidate(choices.filter(x=>x.channel!==1)),/no_valid_mask/);
for(const spec of CHALLENGES){
 const f=challengeFixture(spec.id);
 assert.equal(f.rgb.length,3*n);assert.equal(f.truth.length,n);
 assert.ok(f.truth.some(x=>x===1)&&f.truth.some(x=>x===0));
 for(const [x,y,label] of spec.points)assert.equal(f.truth[y*WIDTH+x],label,spec.id+" prompt");
 const buf=new Uint8Array(3*n);buf.set(f.truth,n);buf.fill(1,2*n);
 assert.equal(chooseCandidate(maskCandidates({...tensor,data:buf},[.9,.8,.99],spec.points)).channel,1);
}
assert.throws(()=>challengeFixture("other"),/unknown_fixture/);
for(const [id,spec] of Object.entries(PHOTO_SPECS))assert.deepEqual(validatePhotoPoints(id,spec.guided),spec.guided);
assert.throws(()=>validatePhotoPoints("unknown",[[1,1,1]]),/invalid_photo_points/);
assert.throws(()=>validatePhotoPoints("coffee",[[600,1,1]]),/invalid_photo_points/);
assert.throws(()=>validatePhotoPoints("coffee",[[1,1,0]]),/invalid_photo_points/);
assert.throws(()=>validatePhotoPoints("coffee",[[1,1,1],[1,1,0]]),/duplicate_photo_point/);
assert.throws(()=>validatePhotoPoints("coffee",Array.from({length:13},(_,i)=>[i,1,1])),/invalid_photo_points/);
console.log("SAM pilot contracts passed (synthetic outputs; not model inference).");
